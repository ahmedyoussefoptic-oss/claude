#!/usr/bin/env node
// Prepares this copy of the system for one school:
//   node setup/configure.mjs school.config.json
// Writes the Firebase settings (.env.local, .firebaserc, functions/.env),
// replaces the school name everywhere it is shown (interface, parent pages,
// WhatsApp / email texts), the default branches and sections, and the logo.
// Safe to run again after editing school.config.json: the names currently
// in the code are remembered in setup/brand.json.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.join(ROOT, p);
const fail = (msg) => { console.error(`\n✖ ${msg}\n`); process.exit(1); };

const configPath = path.resolve(process.argv[2] || rel('school.config.json'));
if (!fs.existsSync(configPath)) fail(`لم يتم العثور على ملف الإعدادات: ${configPath}\nانسخ setup/school.config.example.json إلى school.config.json وعدّله.`);
const cfg = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const s = cfg.school || {};
const fb = cfg.firebase || {};
for (const [k, v] of Object.entries({ logo: cfg.logo, 'school.nameAr': s.nameAr, 'school.shortNameAr': s.shortNameAr, 'school.nameEn': s.nameEn, 'school.shortNameEn': s.shortNameEn, 'firebase.apiKey': fb.apiKey, 'firebase.projectId': fb.projectId, 'firebase.appId': fb.appId, ownerEmail: cfg.ownerEmail })) {
  if (!v || String(v).includes('ضع') || String(v).includes('YOUR_')) fail(`الحقل ${k} مطلوب في ${path.basename(configPath)}`);
}
const projectId = fb.projectId;
const region = fb.functionsRegion || 'us-central1';
const appUrl = (cfg.appUrl || `https://${projectId}.web.app`).replace(/\/+$/, '');

// 1) Firebase settings -------------------------------------------------------
const envLines = {
  VITE_FIREBASE_API_KEY: fb.apiKey,
  VITE_FIREBASE_AUTH_DOMAIN: fb.authDomain || `${projectId}.firebaseapp.com`,
  VITE_FIREBASE_PROJECT_ID: projectId,
  VITE_FIREBASE_STORAGE_BUCKET: fb.storageBucket || `${projectId}.firebasestorage.app`,
  VITE_FIREBASE_MESSAGING_SENDER_ID: fb.messagingSenderId || '',
  VITE_FIREBASE_APP_ID: fb.appId,
  VITE_FIREBASE_VAPID_KEY: fb.vapidKey || '',
  VITE_FUNCTIONS_REGION: region,
};
fs.writeFileSync(rel('.env.local'), `${Object.entries(envLines).map(([k, v]) => `${k}=${v}`).join('\n')}\n`);
fs.writeFileSync(rel('.firebaserc'), `${JSON.stringify({ projects: { default: projectId } }, null, 2)}\n`);
fs.writeFileSync(rel('functions/.env'), [
  '# Generated by setup/configure.mjs',
  `ENABLE_WA_API=${cfg.whatsappApi === true ? 'true' : 'false'}`,
  `SYSTEM_OWNER_EMAIL=${String(cfg.ownerEmail).trim().toLowerCase()}`,
  `PUBLIC_APP_URL=${appUrl}`,
  `SCHOOL_NAME=${s.nameAr}`,
  '',
].join('\n'));
console.log('✔ إعدادات Firebase: .env.local و .firebaserc و functions/.env');

// 2) School name everywhere --------------------------------------------------
const brandFile = rel('setup/brand.json');
const current = JSON.parse(fs.readFileSync(brandFile, 'utf8'));
const next = {
  nameAr: s.nameAr,
  nameArAlt: s.nameAr,
  brandAr: s.brandAr || s.nameAr,
  shortNameAr: s.shortNameAr,
  platformAr: `منصة ${s.shortNameAr}`,
  nameEn: s.nameEn,
  brandEn: s.brandEn || s.nameEn,
  shortNameEn: s.shortNameEn,
  lmsName: s.lmsName || current.lmsName,
};
// Longest first, so "مدارس المكتشف العالمية" is replaced before "المكتشف".
const pairs = [
  ['nameAr'], ['nameArAlt'], ['brandAr'], ['platformAr'], ['shortNameAr'],
  ['nameEn'], ['brandEn'], ['shortNameEn'], ['lmsName'],
].map(([k]) => [current[k], next[k]]).filter(([a, b]) => a && b && a !== b);
const targets = [];
const walk = (dir) => {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) { if (name !== 'node_modules') walk(p); continue; }
    if (/\.(jsx?|json|html|webmanifest|css|md)$/.test(name)) targets.push(p);
  }
};
walk(rel('src'));
targets.push(rel('index.html'), rel('public/manifest.webmanifest'), rel('functions/index.js'));
let changedFiles = 0;
for (const file of targets) {
  const before = fs.readFileSync(file, 'utf8');
  let text = before;
  for (const [from, to] of pairs) text = text.split(from).join(to);
  if (text !== before) { fs.writeFileSync(file, text); changedFiles++; }
}
fs.writeFileSync(brandFile, `${JSON.stringify(next, null, 2)}\n`);
console.log(`✔ اسم المدرسة: ${s.nameAr} (${changedFiles} ملف)`);

// 3) Default branches and sections (until edited in Settings) ----------------
const list = (items, fallback) => (Array.isArray(items) && items.length ? items : fallback)
  .map((b) => `  { id: '${String(b.id).replace(/'/g, '')}', name: '${String(b.name).replace(/'/g, '’')}' },`).join('\n');
const orgFile = rel('src/config/orgData.js');
let org = fs.readFileSync(orgFile, 'utf8');
org = org.replace(/export const BRANCHES = \[[\s\S]*?\];/, `export const BRANCHES = [\n${list(cfg.branches, [{ id: 'MAIN', name: 'الفرع الرئيسي' }])}\n];`);
org = org.replace(/export const DEPARTMENTS = \[[\s\S]*?\];/, `export const DEPARTMENTS = [\n${list(cfg.departments, [{ id: 'GENERAL', name: 'القسم العام' }])}\n];`);
fs.writeFileSync(orgFile, org);
console.log('✔ الفروع والأقسام الافتراضية');

// 4) Logo and app icons ------------------------------------------------------
if (cfg.logo) {
  const logo = path.resolve(path.dirname(configPath), cfg.logo);
  if (!fs.existsSync(logo)) fail(`ملف الشعار غير موجود: ${logo}`);
  if (!/\.png$/i.test(logo)) fail('الشعار يجب أن يكون بصيغة PNG.');
  fs.copyFileSync(logo, rel('src/assets/logo.png'));
  const icons = { 'icon-192.png': 192, 'icon-512.png': 512, 'icon-maskable-192.png': 192, 'icon-maskable-512.png': 512, 'apple-touch-icon.png': 180 };
  let resized = true;
  for (const [name, size] of Object.entries(icons)) {
    const out = rel(`public/icons/${name}`);
    fs.copyFileSync(logo, out);
    try { execFileSync('sips', ['-z', String(size), String(size), out], { stdio: 'ignore' }); } catch { resized = false; }
  }
  let html = fs.readFileSync(rel('index.html'), 'utf8');
  html = html.replace('<link rel="icon" type="image/svg+xml" href="/favicon.svg" />', '<link rel="icon" type="image/png" href="/icons/icon-192.png" />');
  fs.writeFileSync(rel('index.html'), html);
  console.log(`✔ الشعار وأيقونات التطبيق${resized ? '' : ' (نُسخت بدون تغيير المقاس — يُفضّل استبدال public/icons بمقاسات 192 و512)'}`);
}

console.log(`\nتم. الخطوات التالية:\n  npm run build\n  npx firebase-tools deploy\nثم افتح ${appUrl} وسجّل الدخول بحساب ${cfg.ownerEmail}\n`);
